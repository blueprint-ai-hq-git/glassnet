"""glassnet.arith — the verifiable task for Target G.

Single-digit addition written as text, with an answer that can be CHECKED by integer arithmetic.

    problem:  "7+5="        tokens: 7 + 5 =
    answer:   "12"          tokens: 1 2
    sequence: 7 + 5 = 1 2   (6 tokens)

Vocabulary (14): 0-9, '+', '=', '<PAD>', '<BOS>'.

Everything here is our own code. The data is generated by us and the labels are arithmetic --
no external dataset, no licence question, no pretrained anything.
"""
import numpy as np

DIGITS = [str(d) for d in range(10)]
PLUS, EQ, PAD, BOS = "+", "=", "<PAD>", "<BOS>"
VOCAB = DIGITS + [PLUS, EQ, PAD, BOS]
TOKEN = {t: i for i, t in enumerate(VOCAB)}
V = len(VOCAB)                       # 14
WINDOW = 5                           # "a + b =" is 5 tokens; the model predicts what follows
SEQ_LEN = 6                          # a + b = <tens> <units>


def problems():
    """All 100 single-digit addition problems, in a fixed order."""
    return [(a, b) for a in range(10) for b in range(10)]


def answer(a, b):
    return int(a) + int(b)


def encode(a, b):
    """The full 6-token sequence for a problem."""
    s = answer(a, b)
    return np.array([TOKEN[str(a)], TOKEN[PLUS], TOKEN[str(b)], TOKEN[EQ],
                     TOKEN[str(s // 10)], TOKEN[str(s % 10)]], dtype=np.int64)


def prompt(a, b):
    """The 5-token input window."""
    return encode(a, b)[:WINDOW]


def is_correct(seq):
    """THE VERIFIER. Returns True iff the two answer tokens are the true sum.

    This is integer arithmetic, not a model, not a label, not a human. It is the only reason
    Target G can exist: bad data can be identified and thrown away.
    """
    seq = np.asarray(seq)
    if seq.ndim == 1:
        seq = seq[None, :]
    ok = np.zeros(len(seq), dtype=bool)
    for i, s in enumerate(seq):
        a, b = int(s[0]), int(s[2])
        got = int(s[4]) * 10 + int(s[5])
        ok[i] = (got == a + b)
    return ok


def window_targets(seqs, window=WINDOW):
    """Split sequences into (window, next-token) pairs -- what a language model trains on."""
    seqs = np.asarray(seqs)
    X = seqs[:, :window]
    y = seqs[:, window]
    return X, y


# ------------------------------------------------------------------ the readable concepts
def concept_carry(a, b):
    """Is a carry needed? a + b >= 10. The structural concept of this task."""
    return int(a + b >= 10)


def concept_sum_over_9(a, b):
    return int(a + b > 9)


def concept_first_odd(a, b):
    return int(a % 2 == 1)


def concept_second_odd(a, b):
    return int(b % 2 == 1)


def concept_sum_even(a, b):
    return int((a + b) % 2 == 0)


def concept_first_is_nine(a, b):
    return int(a == 9)


def concept_answer_has_two_digits(a, b):
    return int(a + b >= 10)


def concept_same_digits(a, b):
    return int(a == b)


CONCEPTS = [
    ("is_a_carry", concept_carry),
    ("sum_over_nine", concept_sum_over_9),
    ("first_digit_is_odd", concept_first_odd),
    ("second_digit_is_odd", concept_second_odd),
    ("sum_is_even", concept_sum_even),
    ("first_digit_is_nine", concept_first_is_nine),
    ("answer_has_two_digits", concept_answer_has_two_digits),
    ("same_digits", concept_same_digits),
]


def concept_support(X):
    """Support of each concept in a set of 5-token windows, as a fraction."""
    out = []
    for name, fn in CONCEPTS:
        vals = [fn(int(x[0]), int(x[2])) for x in np.asarray(X)]
        out.append(float(np.mean(vals)))
    return out


def build_pool(X, y):
    """The (window, target) pairs plus their concept labels -- the input to the readable model."""
    X = np.asarray(X)
    y = np.asarray(y)
    lab = np.stack([[fn(int(x[0]), int(x[2])) for _, fn in CONCEPTS] for x in X], axis=1)
    return X, y, lab.astype(np.float32)


def summary():
    return {"V": V, "window": WINDOW, "seq_len": SEQ_LEN, "n_problems": len(problems()),
            "concepts": [n for n, _ in CONCEPTS]}
