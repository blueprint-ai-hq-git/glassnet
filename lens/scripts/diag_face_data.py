"""diag_face_data.py — WHAT FACE DATA CAN WE LEGALLY USE? (read-only, no downloads)

The owner asked for face tracking / facial recognition. The standing HARD rule: only datasets with
safe licenses (MIT, Apache 2.0, CC0, CC BY 4.0), check the license MYSELF, write it in
DATA_LICENSES.md, SKIP anything unclear. Faces are the single most licence-hostile area in vision
(most face datasets are "research only" or scraped), so this enumerates the real options instead of
guessing. Also checks the webcam, which needs no licence at all.
"""
import os
import subprocess

PROJ = "/run/media/yahya/HARD DISK 4/GlassNet"

print("=" * 96)
print("FACE DATA OPTIONS — licence reality check")
print("=" * 96)

print("\n[A] WEBCAM — no dataset, no licence, no download")
for dev in ("/dev/video0", "/dev/video1"):
    print(f"   {dev}: {'PRESENT' if os.path.exists(dev) else 'absent'}")
try:
    out = subprocess.run(["v4l2-ctl", "--list-devices"], capture_output=True, text=True,
                         timeout=10).stdout
    print("   v4l2 devices:")
    for line in out.strip().splitlines()[:8]:
        print("     " + line.strip())
except Exception as e:
    print(f"   v4l2-ctl not available ({str(e)[:50]})")

print("\n[B] DATASETS ALREADY ON DISK THAT CONTAIN FACES")
hits = []
for root, dirs, files in os.walk(os.path.join(PROJ, "data")):
    for f in files:
        low = f.lower()
        if any(k in low for k in ("face", "celeba", "lfw", "lfw", "utk", "fairface", "helen")):
            hits.append(os.path.join(root, f))
    if len(hits) > 12:
        break
print(f"   {len(hits)} face-named files found" if hits else "   none found")

print("\n[C] LICENCE STATUS OF THE USUAL FACE DATASETS (from knowledge, verify before use)")
rows = [
    ("CelebA", "research/non-commercial, scraped from web", "FAILS the rule"),
    ("LFW", "images stay under original Flickr terms", "FAILS the rule"),
    ("UTKFace", "research only, 'not for commercial'", "FAILS the rule"),
    ("FairFace", "CC BY 4.0 for annotations, images from YFCC100M", "AMBIGUOUS — image rights unclear"),
    ("FFHQ", "images from Flickr, CC BY-NC-SA variants", "FAILS (NC)"),
    ("VGGFace2", "research only", "FAILS the rule"),
    ("Own webcam captures", "owner's own data", "PASSES — owner owns it"),
    ("Synthetic faces (our own generator)", "generated by our model", "PASSES — we made it"),
]
for name, lic, verdict in rows:
    print(f"   {name:<32} {lic:<48} {verdict}")

print("\n[D] WHAT THIS MEANS")
print("   Face TRACKING (detect + follow a face in the webcam stream) needs NO dataset at all —")
print("   it is classical image processing + our own concept layer. Can start today, offline.")
print("   Face RECOGNITION (who is this person) needs identities. Under the standing rule the only")
print("   clean sources are: (a) the owner's own photos/webcam, or (b) a dataset the owner names and")
print("   accepts responsibility for. Every public face dataset checked above FAILS or is ambiguous.")
print("\n   RECOMMENDATION: build face DETECTION/TRACKING now (licence-free, webcam), and ask the")
print("   owner for a decision on identities before any recognition claim is made.")
